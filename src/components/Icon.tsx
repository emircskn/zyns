/**
 * The line a caller asks for becomes the set's weight: a filled glyph
 * (`fill="currentColor"`) is the solid one, a heavier stroke the bold one.
 */
function weightOf(fill: unknown, strokeWidth: unknown): IconWeight {
  if (fill === "currentColor") return "fill";
  const w = Number(strokeWidth ?? 1.6);
  return w >= 2 ? "bold" : w <= 1.3 ? "light" : "regular";
}

export function Icon({ name, size = 18, strokeWidth, fill, ...rest }: Props) {
  const Glyph = GLYPHS[name];
  return <Glyph size={size} weight={weightOf(fill, strokeWidth)} aria-hidden="true" {...(rest as Record<string, unknown>)} />;
}
